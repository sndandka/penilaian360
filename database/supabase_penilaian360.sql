BEGIN;

SET search_path TO public;

-- Fungsi helper untuk kolom updated_at otomatis (pengganti ON UPDATE CURRENT_TIMESTAMP)
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =========================================================================
-- 1. UNIT_KERJA
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.unit_kerja (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_unit      VARCHAR(30)  NOT NULL UNIQUE,
    nama_unit      VARCHAR(200) NOT NULL,
    jenis_unit     VARCHAR(30)  NOT NULL DEFAULT 'seksi'
                   CHECK (jenis_unit IN (
                       'dinas','sekretariat','bidang','upt','upt_lab',
                       'seksi','sub_bagian_tata_usaha','subbagian','kelompok_fungsional'
                   )),
    parent_id      INTEGER NULL,
    kepala_unit_id INTEGER NULL,
    alamat         TEXT NULL,
    status         VARCHAR(15) NOT NULL DEFAULT 'aktif'
                   CHECK (status IN ('aktif','nonaktif')),
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_unitkerja_parent FOREIGN KEY (parent_id) REFERENCES public.unit_kerja(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_unitkerja_parent ON public.unit_kerja (parent_id);

DROP TRIGGER IF EXISTS trg_unitkerja_updated_at ON public.unit_kerja;
CREATE TRIGGER trg_unitkerja_updated_at
BEFORE UPDATE ON public.unit_kerja
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- =========================================================================
-- 2. JABATAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.jabatan (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_jabatan  VARCHAR(30)  NOT NULL UNIQUE,
    nama_jabatan  VARCHAR(200) NOT NULL,
    jenis_jabatan VARCHAR(20)  NOT NULL DEFAULT 'pelaksana'
                  CHECK (jenis_jabatan IN ('struktural','fungsional','pelaksana')),
    eselon        VARCHAR(10)  NULL,
    level_jabatan INTEGER      NOT NULL DEFAULT 4,
    keterangan    TEXT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================================
-- 3. PEGAWAI
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.pegawai (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nip                 VARCHAR(25)  NOT NULL UNIQUE,
    nip_lama            VARCHAR(20)  NULL,
    nama_lengkap        VARCHAR(150) NOT NULL,
    gelar_depan         VARCHAR(30)  NULL,
    gelar_belakang      VARCHAR(30)  NULL,
    jenis_kelamin       CHAR(1)      NOT NULL DEFAULT 'L' CHECK (jenis_kelamin IN ('L','P')),
    tempat_lahir        VARCHAR(100) NULL,
    tanggal_lahir       DATE         NULL,
    agama               VARCHAR(30)  NULL,
    status_pernikahan   VARCHAR(30)  NULL,
    golongan_ruang      VARCHAR(10)  NULL,
    tmt_golongan        DATE         NULL,
    pendidikan_terakhir VARCHAR(10)  NULL CHECK (pendidikan_terakhir IS NULL OR pendidikan_terakhir IN ('SD','SLTP','SLTA','D-III','D-IV','S-1','S-2','S-3')),
    prodi               VARCHAR(150) NULL,
    tahun_lulus         SMALLINT     NULL,
    jabatan_id          INTEGER      NULL,
    unit_kerja_id       INTEGER      NULL,
    atasan_langsung_id  INTEGER      NULL,
    tmt_jabatan         DATE         NULL,
    status_kepegawaian  VARCHAR(20)  NOT NULL DEFAULT 'PNS'
                        CHECK (status_kepegawaian IN ('PNS','CPNS','PPPK','PPPK_Paruh_Waktu','Honorer')),
    no_hp               VARCHAR(20)  NULL,
    email               VARCHAR(150) NULL,
    alamat              TEXT         NULL,
    foto                VARCHAR(255) NULL,
    status_aktif        VARCHAR(15)  NOT NULL DEFAULT 'aktif'
                        CHECK (status_aktif IN ('aktif','nonaktif','pensiun','mutasi','meninggal')),
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pegawai_jabatan   FOREIGN KEY (jabatan_id)         REFERENCES public.jabatan(id)    ON DELETE SET NULL,
    CONSTRAINT fk_pegawai_unitkerja FOREIGN KEY (unit_kerja_id)      REFERENCES public.unit_kerja(id) ON DELETE SET NULL,
    CONSTRAINT fk_pegawai_atasan    FOREIGN KEY (atasan_langsung_id) REFERENCES public.pegawai(id)    ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_pegawai_unitkerja ON public.pegawai (unit_kerja_id);
CREATE INDEX IF NOT EXISTS idx_pegawai_jabatan   ON public.pegawai (jabatan_id);
CREATE INDEX IF NOT EXISTS idx_pegawai_atasan    ON public.pegawai (atasan_langsung_id);
CREATE INDEX IF NOT EXISTS idx_pegawai_nip       ON public.pegawai (nip);

DROP TRIGGER IF EXISTS trg_pegawai_updated_at ON public.pegawai;
CREATE TRIGGER trg_pegawai_updated_at
BEFORE UPDATE ON public.pegawai
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Lengkapi FK unit_kerja.kepala_unit_id setelah tabel pegawai tersedia
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_unitkerja_kepala') THEN
        ALTER TABLE public.unit_kerja
            ADD CONSTRAINT fk_unitkerja_kepala
            FOREIGN KEY (kepala_unit_id) REFERENCES public.pegawai(id) ON DELETE SET NULL;
    END IF;
END $$;

-- =========================================================================
-- 4. USERS
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pegawai_id    INTEGER      NULL UNIQUE,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    role          VARCHAR(15)  NOT NULL DEFAULT 'pegawai' CHECK (role IN ('super_admin','admin','pegawai')),
    is_registered SMALLINT     NOT NULL DEFAULT 1 CHECK (is_registered IN (0, 1)),
    last_login    TIMESTAMP    NULL,
    status        VARCHAR(15)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif','terkunci')),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_pegawai FOREIGN KEY (pegawai_id) REFERENCES public.pegawai(id) ON DELETE CASCADE
);

DROP TRIGGER IF EXISTS trg_users_updated_at ON public.users;
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- =========================================================================
-- 5. PERIODE_PENILAIAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.periode_penilaian (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_periode            VARCHAR(30)  NOT NULL UNIQUE,
    nama_periode            VARCHAR(150) NOT NULL,
    tahun                   SMALLINT     NOT NULL,
    jenis_periode           VARCHAR(15)  NOT NULL DEFAULT 'tahunan'
                            CHECK (jenis_periode IN ('tahunan','semester','triwulan','bulanan','lainnya')),
    semester                VARCHAR(10)  NOT NULL DEFAULT 'tahunan',
    target_penilaian        VARCHAR(20)  NOT NULL DEFAULT 'semua'
                            CHECK (target_penilaian IN ('semua','golongan_tertentu')),
    target_golongan         VARCHAR(100) NULL,
    tanggal_mulai           DATE         NOT NULL,
    tanggal_selesai         DATE         NOT NULL,
    tanggal_mulai_pengisian TIMESTAMP    NULL,
    tanggal_akhir_pengisian TIMESTAMP    NULL,
    status                  VARCHAR(15)  NOT NULL DEFAULT 'draft'
                            CHECK (status IN ('draft','aktif','ditutup','diarsipkan')),
    keterangan              TEXT         NULL,
    created_by              INTEGER      NULL,
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_periode_creator FOREIGN KEY (created_by) REFERENCES public.users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_periode_status      ON public.periode_penilaian (status);
CREATE INDEX IF NOT EXISTS idx_periode_tahun_jenis ON public.periode_penilaian (tahun, jenis_periode);

-- =========================================================================
-- 6. KATEGORI_PENILAIAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.kategori_penilaian (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_kategori  VARCHAR(20)  NOT NULL UNIQUE,
    nama_kategori  VARCHAR(150) NOT NULL,
    deskripsi      TEXT         NULL,
    bobot_kategori NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    urutan         INTEGER      NOT NULL DEFAULT 0,
    status         VARCHAR(15)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================================
-- 7. INDIKATOR_PENILAIAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.indikator_penilaian (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kategori_id     INTEGER      NOT NULL,
    kode_indikator  VARCHAR(20)  NOT NULL UNIQUE,
    nama_indikator  VARCHAR(200) NOT NULL,
    deskripsi       TEXT         NULL,
    bobot_indikator NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    urutan          INTEGER      NOT NULL DEFAULT 0,
    status          VARCHAR(15)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_indikator_kategori FOREIGN KEY (kategori_id) REFERENCES public.kategori_penilaian(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_indikator_kategori ON public.indikator_penilaian (kategori_id);

-- =========================================================================
-- 8. PERTANYAAN_PENILAIAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.pertanyaan_penilaian (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indikator_id     INTEGER      NOT NULL,
    pertanyaan       TEXT         NOT NULL,
    jenis_pertanyaan VARCHAR(10)  NOT NULL DEFAULT 'skala' CHECK (jenis_pertanyaan IN ('skala','esai')),
    target_relasi    VARCHAR(100) NOT NULL DEFAULT 'atasan,rekan,bawahan,diri',
    bobot            NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    skor_min         INTEGER      NOT NULL DEFAULT 1,
    skor_max         INTEGER      NOT NULL DEFAULT 5,
    urutan           INTEGER      NOT NULL DEFAULT 0,
    status           VARCHAR(15)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pertanyaan_indikator FOREIGN KEY (indikator_id) REFERENCES public.indikator_penilaian(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_pertanyaan_indikator ON public.pertanyaan_penilaian (indikator_id);

-- =========================================================================
-- 9. MAPPING_PENILAI
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.mapping_penilai (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periode_id         INTEGER      NOT NULL,
    pegawai_dinilai_id INTEGER      NOT NULL,
    pegawai_penilai_id INTEGER      NOT NULL,
    jenis_relasi       VARCHAR(15)  NOT NULL CHECK (jenis_relasi IN ('diri','atasan','rekan','bawahan')),
    bobot_relasi       NUMERIC(5,2) NULL,
    status             VARCHAR(15)  NOT NULL DEFAULT 'belum_mulai' CHECK (status IN ('belum_mulai','proses','selesai')),
    tanggal_mulai_isi  TIMESTAMP    NULL,
    tanggal_submit     TIMESTAMP    NULL,
    komentar_masukan   TEXT         NULL,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mapping_periode FOREIGN KEY (periode_id)         REFERENCES public.periode_penilaian(id) ON DELETE CASCADE,
    CONSTRAINT fk_mapping_dinilai FOREIGN KEY (pegawai_dinilai_id) REFERENCES public.pegawai(id)           ON DELETE CASCADE,
    CONSTRAINT fk_mapping_penilai FOREIGN KEY (pegawai_penilai_id) REFERENCES public.pegawai(id)           ON DELETE CASCADE,
    CONSTRAINT unique_mapping UNIQUE (periode_id, pegawai_dinilai_id, pegawai_penilai_id, jenis_relasi)
);
CREATE INDEX IF NOT EXISTS idx_mapping_periode_status ON public.mapping_penilai (periode_id, status);

-- =========================================================================
-- 10. JAWABAN_PENILAIAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.jawaban_penilaian (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapping_id    INTEGER   NOT NULL,
    pertanyaan_id INTEGER   NOT NULL,
    skor          INTEGER   NOT NULL,
    komentar      TEXT      NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_jawaban_mapping    FOREIGN KEY (mapping_id)    REFERENCES public.mapping_penilai(id)      ON DELETE CASCADE,
    CONSTRAINT fk_jawaban_pertanyaan FOREIGN KEY (pertanyaan_id) REFERENCES public.pertanyaan_penilaian(id) ON DELETE CASCADE,
    CONSTRAINT unique_jawaban UNIQUE (mapping_id, pertanyaan_id)
);

-- =========================================================================
-- 11. HASIL_PENILAIAN
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.hasil_penilaian (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periode_id     INTEGER      NOT NULL,
    pegawai_id     INTEGER      NOT NULL,
    nilai_diri     NUMERIC(5,2) NULL,
    nilai_atasan   NUMERIC(5,2) NULL,
    nilai_rekan    NUMERIC(5,2) NULL,
    nilai_bawahan  NUMERIC(5,2) NULL,
    nilai_akhir    NUMERIC(5,2) NULL,
    predikat       VARCHAR(20)  NULL CHECK (predikat IS NULL OR predikat IN ('Sangat Baik','Baik','Cukup','Kurang','Sangat Kurang')),
    tanggal_hitung TIMESTAMP    NULL,
    dihitung_oleh  INTEGER      NULL,
    catatan        TEXT         NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_hasil_periode    FOREIGN KEY (periode_id)    REFERENCES public.periode_penilaian(id) ON DELETE CASCADE,
    CONSTRAINT fk_hasil_pegawai    FOREIGN KEY (pegawai_id)    REFERENCES public.pegawai(id)           ON DELETE CASCADE,
    CONSTRAINT fk_hasil_penghitung FOREIGN KEY (dihitung_oleh) REFERENCES public.users(id)             ON DELETE SET NULL,
    CONSTRAINT unique_hasil UNIQUE (periode_id, pegawai_id)
);
CREATE INDEX IF NOT EXISTS idx_hasil_periode ON public.hasil_penilaian (periode_id);

-- =========================================================================
-- 12. AUDIT_LOG
-- =========================================================================
CREATE TABLE IF NOT EXISTS public.audit_log (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER      NULL,
    modul        VARCHAR(50)  NOT NULL,
    aktivitas    VARCHAR(255) NOT NULL,
    data_sebelum JSONB        NULL,
    data_sesudah JSONB        NULL,
    ip_address   VARCHAR(45)  NULL,
    user_agent   VARCHAR(255) NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_modul   ON public.audit_log (modul);
CREATE INDEX IF NOT EXISTS idx_audit_user    ON public.audit_log (user_id);
CREATE INDEX IF NOT EXISTS idx_audit_created ON public.audit_log (created_at);

