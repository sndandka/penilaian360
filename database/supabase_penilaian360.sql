-- File ini dikonversi khusus untuk di-import ke Supabase (PostgreSQL):
--   1. Buka Supabase Dashboard -> SQL Editor -> New Query
--   2. Paste atau Upload file ini, lalu klik Run
--   3. Script bersifat idempoten (aman dijalankan ulang tanpa duplikasi)
--
-- Berisi:
--   - 13 tabel ternormalisasi di schema public (PostgreSQL IDENTITY + CHECK)
--   - Fungsi & trigger updated_at otomatis
--   - Index & constraint relasi (termasuk FK kepala_unit_id)
--   - Data master & instrumen awal (konfigurasi_sistem, 64 unit kerja,
--     27 jabatan, akun default superadmin & admin, 6 kategori, 6 indikator,
--     dan 40 butir pertanyaan penilaian) + sinkronisasi sequence IDENTITY
